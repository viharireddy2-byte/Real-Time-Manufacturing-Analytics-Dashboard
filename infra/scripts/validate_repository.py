"""Offline repository checks for deployable JSON, links and publication hygiene."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def validate_repository():
    issues = []
    count = 0
    for suffix in ['*.json', '*.ipynb', '.platform']:
        for path in ROOT.rglob(suffix):
            if any(part in {'workload','benchmark-output','.venv','__pycache__'} for part in path.parts):
                continue
            try:
                document = json.loads(path.read_text(encoding='utf-8-sig'))
                count += 1
                if path.suffix == '.ipynb' and any(c.get('outputs') for c in document.get('cells', [])):
                    issues.append(f'{path.relative_to(ROOT)}: committed notebook outputs')
            except (ValueError, UnicodeError) as error:
                issues.append(f'{path.relative_to(ROOT)}: {error}')
    editorial = re.compile(r'(?i)hiring.manager|recruiter.facing|\bfaang\b|as an ai|generated by chatgpt|private review|my strict rating')
    unsupported = re.compile(r'(?i)reduces unplanned downtime by up to|increases overall equipment effectiveness.*15|ensures 99\.9%|six sigma.*[<≤]2%')
    for path in ROOT.rglob('*.md'):
        if any(part in {'workload','benchmark-output','.venv'} for part in path.parts):
            continue
        for line, value in enumerate(path.read_text().splitlines(), 1):
            if editorial.search(value) or unsupported.search(value):
                issues.append(f'{path.relative_to(ROOT)}:{line}: editorial or unsupported claim')
    # Check central public navigation; legacy screenshot guides are separately maintained.
    for name in ['README.md','docs/DeploymentGuide.md','docs/TechnicalArchitecture.md','docs/DataContracts.md','docs/Operations.md','docs/Performance.md','docs/EngineeringChanges.md']:
        path = ROOT/name
        for target in re.findall(r'\]\(([^)]+)\)',path.read_text()):
            if not target.startswith(('http:', 'https:', '#', 'mailto:')):
                if not (path.parent/target.split('#')[0]).exists():
                    issues.append(f'{name}: broken link {target}')
    return {'json_files_checked': count, 'issues': issues, 'passed': not issues}


if __name__ == '__main__':
    result = validate_repository()
    print(json.dumps(result, indent=2))
    if not result['passed']:
        raise SystemExit(1)
